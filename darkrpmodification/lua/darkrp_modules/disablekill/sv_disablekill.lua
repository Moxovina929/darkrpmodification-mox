--[[---------------------------------------------------------------------------
Запрет самоубийства через консоль
---------------------------------------------------------------------------
Блокирует консольные команды kill и explode для всех игроков.
---------------------------------------------------------------------------]]

hook.Add("CanPlayerSuicide", "DarkRP_DisableKill", function(ply)
    DarkRP.notify(ply, 1, 4, "Самоубийство запрещено!")
    return false
end)
