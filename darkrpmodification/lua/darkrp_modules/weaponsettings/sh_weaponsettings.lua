local function edit()
--[[
---------------------------------------------------------------------------
Модуль изменения настроек оружия
---------------------------------------------------------------------------

Этот модуль позволяет менять настройки оружия. Вот как это работает.
Для каждого оружия и настройки добавляется строка в таком формате:
weapon "КЛАСС ОРУЖИЯ".НАСТРОЙКА = ЗНАЧЕНИЕ



ВАЖНО:
    - Обратите внимание на кавычки вокруг класса оружия!
    - Обратите внимание на '.' между классом и настройкой!
    - Регистр ВАЖЕН. PrintName — это НЕ ТО ЖЕ САМОЕ, что printname!
    - ИЗМЕНЕНИЕ НАСТРОЕК — ЭТО НЕ ПЕРЕПИСЫВАНИЕ ОРУЖИЯ. ПОЖАЛУЙСТА, НЕ ТРОГАЙТЕ ПОЛЕ АВТОРОВ. СПАСИБО.
    - Технически можно изменить любое поле оружия. Опытные пользователи могут даже переопределить, например, PrimaryAttack.
    - Система работает не только с оружием, которое идёт вместе с DarkRP.

Примеры:

-- По сути, это работает как замена "SWEP" в начале каждой настройки, например "SWEP.Primary.Ammo = "pistol""
в этом файле превращается в "weapon_deagle2".Primary.Ammo = "ar2"

-- Установить название шокера "bash baton". Примечание: кавычки важны!
weapon "stunstick".PrintName = "Bash baton"

-- Установить инструкцию для дубинки ареста. Обратите внимание на кавычки! '\n' — это перенос строки.
weapon "arrest_stick".Instructions = "Left click to arrest\nRight click to switch batons"

-- Установить урон p228 в 20 за выстрел. Примечание: у 20 НЕТ кавычек, потому что это просто число.
weapon "weapon_p2282".Primary.Damage = 20


СПИСОК СТАНДАРТНОГО ОРУЖИЯ DARKRP:
Классы стандартного оружия DarkRP перечислены на этой странице:
