НЕКОТОРЫЕ НАСТРОЙКИ, КОТОРЫЕ МОЖНО ТАК ИЗМЕНИТЬ:
    - PrintName     (название)
    - Instructions  (инструкция)
    - Contact       (контакт)
    - Purpose       (назначение)
    - Category      (категория)
    - Recoil        (отдача)
    - Damage        (урон)
    - NumShots      (пуль за выстрел)
    - Cone          (разброс)
    - ClipSize      (размер магазина)
    - Delay         (задержка между выстрелами)
    - DefaultClip   (патронов при выдаче)

