--[[---------------------------------------------------------------------------
Отключение писка при смерти
---------------------------------------------------------------------------
Убирает стандартный звук смерти из sandbox (писк кардиомонитора).
Если хук возвращает true, игра не проигрывает стандартный звук смерти.
---------------------------------------------------------------------------]]

hook.Add("PlayerDeathSound", "DarkRP_NoDeathSound", function(ply)
    return true
end)
