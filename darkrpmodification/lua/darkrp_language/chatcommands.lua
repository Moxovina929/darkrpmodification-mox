Файл перевода описаний чат-команд (переведён на русский)
---------------------------------------------------------------------------

Этот файл содержит переводы описаний чат-команд.
Слева — чат-команда, справа — её описание.
При переводе описаний не удаляйте кавычки (" ") и запятые!

= Внимание =
Иногда при обновлении DarkRP чат-команды добавляются, изменяются и/или удаляются.
По умолчанию для непереведённых команд используется английское описание.
Переводы несуществующих команд просто игнорируются.


= Как перевести недостающие чат-команды =
1. Запустите сервер
2. Зайдите на него
3. В консоли введите команду:
    darkrp_translateChatCommands
4. Вернитесь в этот файл
5. Вставьте результат туда, где написано "-- Новые переводы чат-команд добавляйте под этой строкой:"

= Примечание =
Убедитесь, что код языка в самом низу файла указан правильно.

= Использование языка =
Убедитесь, что convar gmod_language установлен на код вашего языка. Это можно сделать в CFG-файле сервера.
